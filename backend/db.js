const Database = require("better-sqlite3");
const { Pool } = require("pg");
const deasync = require("deasync");
const path = require("path");
const fs = require("fs");
require('./environment');
const { hashPassword } = require("./utils/password");

const databasePath =
  process.env.DATABASE_PATH ||
  path.join(__dirname, "..", "database", "winabwangu.db");

function normalizeSqlForPostgres(sql) {
  let normalized = String(sql || "").trim();
  const ignoreConflicts = /\bINSERT\s+OR\s+IGNORE\s+INTO\b/i.test(normalized);

  normalized = normalized.replace(
    /datetime\(\s*['"]now['"]\s*\)/gi,
    "CURRENT_TIMESTAMP",
  );
  normalized = normalized.replace(
    /datetime\(\s*['"]now['"]\s*,\s*['"]localtime['"]\s*\)/gi,
    "CURRENT_TIMESTAMP",
  );
  normalized = normalized.replace(
    /\bINSERT\s+OR\s+IGNORE\s+INTO\b/gi,
    "INSERT INTO",
  );
  normalized = normalized.replace(
    /\bINTEGER\s+PRIMARY\s+KEY\s+AUTOINCREMENT\b/gi,
    "INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY",
  );

  let paramIndex = 0;
  normalized = normalized.replace(/\?/g, () => `$${++paramIndex}`);

  if (
    ignoreConflicts &&
    /\bVALUES\b/i.test(normalized) &&
    !/\bON\s+CONFLICT\b/i.test(normalized)
  ) {
    normalized = normalized.replace(/(\s*;?\s*)$/, " ON CONFLICT DO NOTHING$1");
  }

  return normalized;
}

function createSqliteDb() {
  if (databasePath !== ':memory:') fs.mkdirSync(path.dirname(databasePath), { recursive: true });
  const db = new Database(databasePath);
  db.pragma("foreign_keys = ON");
  db.pragma("recursive_triggers = ON");

  const schemaPath = path.join(__dirname, "..", "database", "schema.sql");
  const schema = fs.readFileSync(schemaPath, "utf8");
  db.exec(schema);

  const migrations = [
    ["services", "identifier_type", "TEXT NOT NULL DEFAULT 'phone'"],
    ["transactions", "phone_number", "TEXT NOT NULL DEFAULT ''"],
    ["transactions", "account_number", "TEXT NOT NULL DEFAULT ''"],
  ];

  for (const [table, column, definition] of migrations) {
    const hasColumn = db
      .prepare(`PRAGMA table_info(${table})`)
      .all()
      .some((entry) => entry.name === column);

    if (!hasColumn) {
      db.exec(`ALTER TABLE ${table} ADD COLUMN ${column} ${definition}`);
    }
  }

  db.prepare(
    "UPDATE services SET identifier_type = 'account' WHERE service IN ('Zanaco', 'FNB') AND identifier_type = 'phone'",
  ).run();

  return db;
}

function createPostgresDb() {
  const pool = new Pool({
    connectionString: process.env.DATABASE_URL,
    ssl: process.env.DATABASE_SSL === "false" ? false : { rejectUnauthorized: false },
  });

  let transactionClient = null;

  function executeQuery(sql, params = []) {
    const normalized = normalizeSqlForPostgres(sql);
    const values = Array.isArray(params) ? params.flat() : [params];

    return deasync((done) => {
      (transactionClient || pool).query(normalized, values, done);
    })();
  }

  function ensurePostgresSchema() {
    const schemaPath = path.join(__dirname, "..", "database", "schema.sql");
    const schema = fs.readFileSync(schemaPath, "utf8");
    const statements = schema
      .split(/;\s*\n+/)
      .map((statement) => statement.trim())
      .filter(Boolean);

    for (const statement of statements) {
      executeQuery(statement);
    }

    const migrations = [
      ["services", "identifier_type", "TEXT NOT NULL DEFAULT 'phone'"],
      ["transactions", "phone_number", "TEXT NOT NULL DEFAULT ''"],
      ["transactions", "account_number", "TEXT NOT NULL DEFAULT ''"],
    ];

    for (const [table, column, definition] of migrations) {
      const result = executeQuery(
        `SELECT EXISTS (
          SELECT 1 FROM information_schema.columns
          WHERE table_schema = current_schema() AND table_name = $1 AND column_name = $2
        ) AS exists;`,
        [table, column],
      );

      if (!result.rows?.[0]?.exists) {
        executeQuery(
          `ALTER TABLE ${table} ADD COLUMN ${column} ${definition};`,
        );
      }
    }

    executeQuery(
      "UPDATE services SET identifier_type = 'account' WHERE service IN ('Zanaco', 'FNB') AND identifier_type = 'phone'",
    );
  }

  ensurePostgresSchema();

  const db = {
    prepare(sql) {
      const normalized = normalizeSqlForPostgres(sql);

      return {
        get(...args) {
          const result = executeQuery(normalized, args);
          return result.rows?.[0] ?? null;
        },
        all(...args) {
          const result = executeQuery(normalized, args);
          return result.rows ?? [];
        },
        run(...args) {
          let finalSql = normalized;
          if (
            /^\s*INSERT\b/i.test(finalSql) &&
            !/\bRETURNING\b/i.test(finalSql)
          ) {
            finalSql = `${finalSql.replace(/;\s*$/, "")} RETURNING *`;
          }

          const result = executeQuery(finalSql, args);
          return {
            changes: result.rowCount ?? 0,
            lastInsertRowid: result.rows?.[0]?.id ?? null,
          };
        },
      };
    },
    exec(sql) {
      executeQuery(sql);
    },
    transaction(callback) {
      return (...args) => {
        const client = deasync((done) => pool.connect(done))();
        const previousClient = transactionClient;
        transactionClient = client;
        try {
          executeQuery("BEGIN");
          const result = callback(...args);
          executeQuery("COMMIT");
          return result;
        } catch (error) {
          executeQuery("ROLLBACK");
          throw error;
        } finally {
          transactionClient = previousClient;
          client.release();
        }
      };
    },
    close() {
      return pool.end();
    },
  };

  return db;
}

